from sim.service import CATCH, HELLO, SimService

# The Packet v1 specification's worked exchange, not generated by the code tested.
PING = bytes.fromhex("1001c000000501000000c03e")
REPLY = bytes.fromhex(
    "0002c00000181101000000000000000000006400000000000000010000e136"
)


class ScriptClient:
    """An ASGI transport whose binary send can be held or fail deterministically."""

    def __init__(self, bridge, config, *, blocked=False, fail_send=False):
        self.bridge = bridge
        self.config = config
        self.incoming = asyncio.Queue()
        self.outgoing = asyncio.Queue()
        self.sending = asyncio.Event()
        self.release = asyncio.Event()
        if not blocked:
            self.release.set()
        self.fail_send = fail_send

    async def __aenter__(self):
        scope = {
            "type": "websocket",
            "root_path": "",
            "query_string": b"",
            "path": urlsplit(self.config["url"]).path,
            "headers": [
                (b"authorization", f"Bearer {self.config['credential']}".encode())
            ],
        }
        self.incoming.put_nowait({"type": "websocket.connect"})
        self.task = asyncio.create_task(
            self.bridge.app(scope, self.incoming.get, self._send)
        )
        return self

    async def _send(self, message):
        if message["type"] == "websocket.send" and "bytes" in message:
            self.sending.set()
            await self.release.wait()
            if self.fail_send:
                raise OSError("Script connection lost during send")
        self.outgoing.put_nowait(message)

    def send_packet(self, packet):
        self.incoming.put_nowait({"type": "websocket.receive", "bytes": packet})

    def disconnect(self):
        self.incoming.put_nowait({"type": "websocket.disconnect", "code": 1000})

    async def receive(self):
        return await asyncio.wait_for(self.outgoing.get(), 2)

    async def __aexit__(self, *exc):
        self.disconnect()
        await asyncio.wait_for(self.task, 2)


@pytest.fixture
def run_session(tmp_path, monkeypatch):
    def run(check, challenge=HELLO):
        async def exercise():
            progress.migrate()
            if challenge == CATCH:
                progress.save_completion("ready-for-the-pass")
            controller = SimpleNamespace(
                storage=SimpleNamespace(paths={"bridge": tmp_path}),
                create=AsyncMock(),
                destroy=AsyncMock(),
            )
            bridge = ScriptBridge()
            # Exercise bridge.app directly; no Unix socket, chown or Uvicorn.
            monkeypatch.setattr(bridge, "start", AsyncMock())
            time = ManualTime()
            engine = SessionService(
                controller,
                bridge,
                SimService(time, time),
                {HELLO: ChallengeFiles({}, {}), CATCH: ChallengeFiles({}, {})},
            )

            def config():
                resources = controller.create.call_args.kwargs["resources"]
                return json.loads(resources["connection.json"])

            try:
                await engine.start(challenge)
                await check(engine, config)
            finally:
                await engine.stop()

        asyncio.run(exercise())

    return run


def test_reply_counts_only_after_transport_send_finishes(run_session):
    async def check(engine, config):
        async with ScriptClient(engine.bridge, config(), blocked=True) as client:
            assert (await client.receive())["type"] == "websocket.accept"
            client.send_packet(PING)
            await asyncio.wait_for(client.sending.wait(), 2)
            view = engine.read()
            assert view.state.commands_received == 1
            assert not view.goal_reached
            assert view.completion == "not_yet"

            client.release.set()
            assert (await client.receive())["bytes"] == REPLY
            assert engine.read().goal_reached

    run_session(check)


@pytest.mark.parametrize("failure", ["send_error", "disconnect"])
def test_unsent_reply_cannot_complete_hello_and_next_connection_works(
    run_session, failure
):
    async def check(engine, config):
        async with ScriptClient(
            engine.bridge, config(), blocked=True, fail_send=failure == "send_error"
        ) as client:
            assert (await client.receive())["type"] == "websocket.accept"
            client.send_packet(PING)
            await asyncio.wait_for(client.sending.wait(), 2)
            if failure == "send_error":
                client.release.set()
            else:
                client.disconnect()
            await asyncio.wait_for(client.task, 2)
            assert not engine.read().goal_reached
            assert engine.read().state.commands_received == 1
            assert client.outgoing.empty()

        async with ScriptClient(engine.bridge, config()) as next_client:
            assert (await next_client.receive())["type"] == "websocket.accept"
            next_client.send_packet(PING)
            assert (await next_client.receive())["type"] == "websocket.send"
            assert engine.read().goal_reached
            assert engine.read().state.commands_received == 2

    run_session(check)


def test_stop_during_send_does_not_complete_or_admit_old_credentials(run_session):
    async def check(engine, config):
        old_config = config()
        async with ScriptClient(engine.bridge, old_config, blocked=True) as client:
            assert (await client.receive())["type"] == "websocket.accept"
            client.send_packet(PING)
            await asyncio.wait_for(client.sending.wait(), 2)
            await engine.stop()
            assert (await client.receive())["type"] == "websocket.close"
            # A send already inside the transport can finish after revocation.
            client.release.set()
            await client.receive()
            assert engine.read() is None
            assert progress.read_completed() == set()

        await engine.start(HELLO)
        fresh_config = config()
        assert fresh_config["credential"] != old_config["credential"]
        for rejected in (
            old_config,
            {**fresh_config, "credential": old_config["credential"]},
        ):
            async with ScriptClient(engine.bridge, rejected) as stale:
                refusal = await stale.receive()
                assert refusal["type"] == "websocket.close"
                assert refusal["code"] == 1008
        assert engine.read().history == []
        assert not engine.read().goal_reached
        async with ScriptClient(engine.bridge, fresh_config) as fresh:
            assert (await fresh.receive())["type"] == "websocket.accept"
            fresh.send_packet(PING)
            assert (await fresh.receive())["bytes"] == REPLY
            assert engine.read().goal_reached

    run_session(check)


def test_catch_disconnect_releases_receiver_without_restarting_session(run_session):
    async def check(engine, config):
        current = engine.read()
        async with ScriptClient(engine.bridge, config()) as first:
            assert (await first.receive())["type"] == "websocket.accept"
            ready = json.loads((await first.receive())["text"])
            assert ready == {
                "type": "ready", "pass_run_id": current.pass_view.pass_run_id
            }
            assert engine.read().pass_view.receiver_ready
            async with ScriptClient(engine.bridge, config()) as duplicate:
                assert (await duplicate.receive())["type"] == "websocket.accept"
                assert json.loads((await duplicate.receive())["text"])["code"] == (
                    "RECEIVER_BUSY"
                )
            assert engine.read().pass_view.receiver_ready

        assert not engine.read().pass_view.receiver_ready
        async with ScriptClient(engine.bridge, config()) as replacement:
            assert (await replacement.receive())["type"] == "websocket.accept"
            assert json.loads((await replacement.receive())["text"]) == ready
            replacement.send_packet(PING)
            assert json.loads((await replacement.receive())["text"])["code"] == (
                "WRONG_CHALLENGE"
            )
        view = engine.read()
        assert view.session_id == current.session_id
        assert view.pass_view.status == "not_started"
        assert not view.pass_view.receiver_ready
        assert view.history == [] and not view.goal_reached

    run_session(check, challenge=CATCH)
