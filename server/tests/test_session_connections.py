"""Real Session/bridge/Sim protocol checks without Docker or a socket listener.

Only container preparation and listener startup are substituted. These checks
do not prove container isolation, process cleanup or Workspace persistence;
tests/runtime/test_session_engine.py retains that real-Docker coverage.

These cover KSAT-12's script connections, not KSAT-38/64's browser terminal
or KSAT-62/63's HTTP routes. KSAT-65 owns when verified Hello evidence is saved.
"""

import asyncio
import json
from types import SimpleNamespace
from unittest.mock import AsyncMock
from urllib.parse import urlsplit

import pytest

from api import progress
